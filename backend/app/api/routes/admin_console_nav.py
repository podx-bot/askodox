"""ONE map of the Command Center console (/admin/console).

Main heading -> category -> page, each page exactly once (no duplicates), with
English + Telugu names and a short guide (what this page is / what to do).
The console draws its sidebar, the home grid, the section grids, the
breadcrumbs, the page search and the per-page guide from this list only.

A page is either a console view (``view``, drawn by a JS function of the same
name, gated by ``perm``) or a schema resource (``res``; its permission comes
from the platform schema). ``tests/test_admin_console_nav.py`` checks that
every console view and every schema resource is listed exactly once.
"""
from __future__ import annotations

from typing import Any, Dict, List


def _v(view: str, perm: str, en: str, te: str, what_en: str, what_te: str,
       do_en: str, do_te: str) -> Dict[str, str]:
    return {"id": view, "perm": perm, "en": en, "te": te, "what_en": what_en,
            "what_te": what_te, "do_en": do_en, "do_te": do_te}


def _r(res: str, en: str, te: str, what_en: str, what_te: str, do_en: str,
       do_te: str) -> Dict[str, str]:
    return {"id": "r:" + res, "res": res, "en": en, "te": te, "what_en": what_en,
            "what_te": what_te, "do_en": do_en, "do_te": do_te}


def _cat(en: str, te: str, items: List[Dict[str, str]]) -> Dict[str, Any]:
    return {"en": en, "te": te, "items": items}



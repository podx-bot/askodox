"""Business Kit (owner 2026-11-24): ONE registry of business categories -> sub-categories, and for each sub-category
how that business works in ASKODOX. A shop picks a MAIN sub-category and any number of MORE (a hotel that also sells
sweets and cakes, a furniture shop that also sells taps, motors and geysers); everything below follows those picks:

* ``flows`` -- the ways of working (``FLOWS``): 1 counter sale, 2 menu + table + kitchen, 3 booking / rental by date
  and time, 4 job card / order ahead, 5 monthly / subscription, 6 enquiry -> visit -> deal. A mixed shop gets the
  union of its picks' flows; the app chooses the shop's pages from them (``page_family``), never from a category name.
* ``kind`` -- the POS business type (``pos_store.TEMPLATES``) the shop takes from its MAIN pick, and ``catalogue`` --
  the ready item list + item details (``catalogue_templates``).
* ``details`` -- what an item / service of this kind carries; ``asks`` -- what customers usually ask such a business
  (answered from the shop's OWN answers, ``shop_follows``); ``try_on`` -- whether the item can be shown on the
  customer's own photo (``on_me``) or in a photo of their home (``in_home``).

The defaults below are seeded ONCE into the Command Center resource ``business_kit`` (``seed_defaults``); from then on
staff add, change, pause or move categories and sub-categories there without an app update (``set_source``). A record
without ``parent`` is a category; with ``parent`` it is a sub-category of that category. Keys are stable ids: a shop
stores keys, so a key is never reused for another business.
"""

_SOURCE: Optional[Callable[[], list]] = None
_CACHE: Dict[str, Any] = {"at": 0.0, "value": None, "key": None}
CACHE_SECONDS = 30.0


def set_source(reader: Optional[Callable[[], list]], key: Any = None) -> None:
    """The Command Center records (routes/platform.py, called on every platform() use). None = code defaults only.
    The cache starts over only when the store changes (``key`` = its database path) or an edit calls ``refresh``."""
    global _SOURCE
    _SOURCE = reader
    if reader is None or key != _CACHE["key"]:
        _CACHE.update(at=0.0, value=None, key=key)


def refresh() -> None:
    _CACHE.update(at=0.0, value=None)


def _list(value: Any, separators: str = r"[\n,·]") -> List[str]:
    if isinstance(value, str):
        value = [v for v in re.split(separators, value)]
    return [str(v).strip() for v in (value or []) if str(v).strip()] if isinstance(value, (list, tuple, str)) else []


def _active(row: Dict[str, Any]) -> bool:
    return not row.get("archived") and str(row.get("status") or "ACTIVE").upper() == "ACTIVE"


def _build() -> List[Dict[str, Any]]:
    cats: Dict[str, Dict[str, Any]] = {}
    subs: Dict[str, Dict[str, Any]] = {}
    for order, cat in enumerate(DEFAULT_CATEGORIES):
        cats[cat["key"]] = {k: v for k, v in cat.items() if k != "subs"}
        cats[cat["key"]]["order"] = order * 100
        for i, sub in enumerate(cat["subs"]):
            subs[sub["key"]] = {**copy.deepcopy(sub), "parent": cat["key"], "order": i}
    rows: list = []
    if _SOURCE is not None:
        try:
            rows = list(_SOURCE() or [])
        except Exception:
            rows = []
    for row in rows:
        data = row.get("data") or {}
        key = str(data.get("key") or "").strip().casefold()
        if not key:
            continue
        parent = str(data.get("parent") or "").strip().casefold()
        if not _active(row):
            (subs if parent else cats).pop(key, None)
            continue
        en = str(data.get("label_en") or key)
        names = {"en": en, "te": str(data.get("label_te") or en), "hi": str(data.get("label_hi") or en)}
        order = data.get("order")
        if not parent:
            old = cats.get(key, {})
            cats[key] = {**old, "key": key, **names,
                         "order": int(order) if isinstance(order, (int, float)) else old.get("order", 10_000)}
            continue
        old = subs.get(key, {})
        flows = [f for f in _list(data.get("flows")) if f in FLOWS] or old.get("flows") or ["1"]
        try_on = str(data.get("try_on") or "")
        subs[key] = {
            **old, "key": key, **names, "parent": parent, "flows": flows,
            "kind": str(data.get("shop_kind") or old.get("kind") or "general"),
            "catalogue": str(data.get("catalogue_template") or old.get("catalogue") or ""),
            "details": str(data.get("details") or old.get("details") or ""),
            "asks": _list(data.get("customer_questions"), r"[\n·]") or old.get("asks") or [],
            "try_on": try_on if try_on in TRY_ON_KINDS else "",
            "try_on_note": str(data.get("try_on_note") or ""),
            "aliases": _list(data.get("aliases")),
            "high_stakes": bool(data.get("high_stakes")),
            "order": int(order) if isinstance(order, (int, float)) else old.get("order", 10_000),
        }
    out = []
    for cat in sorted(cats.values(), key=lambda c: c.get("order", 0)):
        mine = sorted((s for s in subs.values() if s["parent"] == cat["key"]), key=lambda s: s.get("order", 0))
        if mine:
            out.append({**cat, "hi": cat.get("hi") or cat["en"],
                        "subs": [{**s, "hi": s.get("hi") or s["en"]} for s in mine]})
    return out


def categories() -> List[Dict[str, Any]]:
    """Categories (each with its sub-categories), Command Center edits included. Cached for a few seconds."""
    now = time.monotonic()
    if _CACHE["value"] is None or now - _CACHE["at"] > CACHE_SECONDS:
        _CACHE["value"], _CACHE["at"] = _build(), now
    return _CACHE["value"]


def _subs() -> Dict[str, Dict[str, Any]]:
    return {s["key"]: s for c in categories() for s in c["subs"]}


def sub(key: str) -> Optional[Dict[str, Any]]:
    return _subs().get(str(key or "").strip().casefold())


def category(key: str) -> Optional[Dict[str, Any]]:
    return next((c for c in categories() if c["key"] == str(key or "").strip().casefold()), None)


def picker() -> List[Dict[str, Any]]:
    """What the app's category pickers show (the old shape + the kit's own fields)."""
    return [{"key": c["key"], "en": c["en"], "te": c["te"], "hi": c["hi"],
             "subs": [{"key": s["key"], "en": s["en"], "te": s["te"], "hi": s["hi"], "flows": s["flows"],
                       "details": s["details"], "asks": s["asks"], "try_on": s["try_on"],
                       "high_stakes": s["high_stakes"]} for s in c["subs"]]} for c in categories()]


def flows_info() -> List[Dict[str, Any]]:
    return [{"key": k, **v} for k, v in FLOWS.items()]


def labels(category_key: str, subcategory_key: str) -> Dict[str, Dict[str, str]]:
    """Readable names for stored keys ("other:<words>" shows the words as typed). A sub-category is found by its own
    key whatever category it now sits under (staff may move it)."""
    out: Dict[str, Dict[str, str]] = {}
    top = category(category_key)
    if top:
        out["category"] = {"en": top["en"], "te": top["te"]}
    elif category_key:
        words = category_key.split(":", 1)[1] if category_key.startswith("other:") else category_key
        out["category"] = {"en": words, "te": words}
    if subcategory_key:
        found = sub(subcategory_key)
        words = subcategory_key.split(":", 1)[1] if subcategory_key.startswith("other:") else subcategory_key
        out["subcategory"] = {"en": found["en"], "te": found["te"]} if found else {"en": words, "te": words}
    return out


def parse_more(value: Any, main: str = "") -> List[str]:
    """The extra picks as known sub-category keys (comma separated or a list), the main one left out, at most 12."""
    known = _subs()
    seen: List[str] = []
    for key in _list(value):
        key = key.casefold()
        if key in known and key != main and key not in seen:
            seen.append(key)
    return seen[:MAX_MORE]


def page_family(flows: Iterable[str], main_flows: Optional[List[str]] = None) -> str:
    """Which shop pages fit: food (menu, tables, kitchen) when any pick has flow 2; service (orders & bookings,
    services & prices) when the MAIN pick works mainly by booking / job card / month / enquiry (its first flow), or
    no pick sells at a counter; else retail (items & stock)."""
    flows = set(flows)
    if "2" in flows:
        return "food"
    if main_flows:
        return "retail" if main_flows[0] == "1" else "service"
    if flows and "1" not in flows:
        return "service"
    return "retail"


def shop_kit(category_key: str, subcategory_key: str, more: Any = "", template: str = "") -> Dict[str, Any]:
    """Everything a shop's picks decide. With no pick yet, the main pick follows the shop's kind (template)."""
    main = sub(subcategory_key)
    inferred = False
    if main is None and template:
        main = sub(KIND_DEFAULT_SUB.get(template, ""))
        inferred = main is not None
    picks = ([main] if main else []) + [s for s in (sub(k) for k in parse_more(more, main["key"] if main else "")) if s]
    flows = sorted({f for s in picks for f in s["flows"]})
    return {
        "main": main["key"] if main else None,
        "inferred": inferred,
        "subs": [s["key"] for s in picks],
        "names": [{"key": s["key"], "en": s["en"], "te": s["te"]} for s in picks],
        "flows": flows,
        "page_family": page_family(flows, main["flows"] if main else None),
        "kind": main["kind"] if main else (template or "general"),
        "catalogue": main["catalogue"] if main else "",
        "try_on": sorted({s["try_on"] for s in picks if s["try_on"]}),
        "high_stakes": any(s["high_stakes"] for s in picks),
    }


def questions(sub_keys: Iterable[str]) -> List[Dict[str, Any]]:
    """What customers usually ask the businesses picked: one entry per question, keyed '<sub>.<n>'."""
    out: List[Dict[str, Any]] = []
    seen: set = set()
    for key in sub_keys:
        found = sub(key)
        if not found:
            continue
        for i, text in enumerate(found["asks"]):
            if text in seen:
                continue
            seen.add(text)
            out.append({"key": f"{found['key']}.{i}", "question": text, "sub": found["key"],
                        "sub_en": found["en"], "sub_te": found["te"]})
    return out


# ---- matching a customer's words to a question the shop can answer (any script; no model call)

_TOKEN = re.compile(r"[a-z0-9\u0900-\u097f\u0b80-\u0bff\u0c00-\u0c7f\u0c80-\u0cff\u0d00-\u0d7f]+")
# Question / filler words: they say a question is asked, not WHAT is asked.
_FILLER = {
    "ఎంత", "ఉందా", "ఉన్నాయా", "ఏంటి", "ఏమిటి", "ఎప్పుడు", "ఎన్ని", "ఎక్కడ", "ఎలా", "నా", "మీ", "మా", "ఈ", "ఆ", "ఇది",
    "అది", "ఒక", "కి", "లో", "నుంచి", "కూడా", "అయితే", "ఇప్పుడు", "the", "a", "an", "is", "are", "do", "does", "you",
    "your", "can", "have", "has", "there", "what", "how", "much", "when", "where", "which", "any", "for", "to", "of",
    "in", "on", "it", "kya", "hai", "ka", "ki", "ke", "aap", "me", "mein", "kitna", "kab", "kahan", "kaise",
}
_QUESTION_CUES = {
    "ఉందా", "ఉన్నాయా", "ఇస్తారా", "చేస్తారా", "వస్తారా", "తీసుకుంటారా", "పంపుతారా", "ఎంత", "ఎప్పుడు", "ఎక్కడ", "ఎలా",
    "ఎన్ని", "ఏంటి", "how", "what", "when", "where", "which", "does", "kya", "kab", "kahan", "kitna", "kaise",
}


def tokens(text: str) -> List[str]:
    return [t for t in _TOKEN.findall(str(text or "").lower()) if len(t) >= 2]


def _same(a: str, b: str) -> bool:
    """One word in two forms (ఇంటికి / ఇంటికీ, deliver / delivery): equal, or one starts the other (4+ letters)."""
    if a == b:
        return True
    short, long_ = (a, b) if len(a) <= len(b) else (b, a)
    return len(short) >= 4 and long_.startswith(short)


def match_question(text: str, candidates: Iterable[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    """The candidate question the customer's words ask, or None. Needs the question's own words (fillers left out):
    at least half of them, and two when the question has two or more."""
    said = [t for t in tokens(text) if t not in _FILLER]
    if not said:
        return None
    best: Optional[tuple] = None
    for cand in candidates:
        want = list(dict.fromkeys(t for t in tokens(cand.get("question", "")) if t not in _FILLER))
        if not want:
            continue
        hits = sum(1 for w in want if any(_same(w, t) for t in said))
        if hits < min(2, len(want)) or hits * 2 < len(want):
            continue
        score = (hits / len(want), hits)
        if best is None or score > best[0]:
            best = (score, cand)
    return best[1] if best else None


def looks_like_question(text: str) -> bool:
    words = tokens(text)
    return len(words) >= 3 and ("?" in str(text or "") or any(w in _QUESTION_CUES for w in words))


def seed_defaults(resources: Any) -> int:
    """Seed the Command Center store once (never over staff edits): one record per category and per sub-category."""
    if resources.repo.list("business_kit", include_archived=True):
        return 0
    count = 0
    for order, cat in enumerate(DEFAULT_CATEGORIES):
        resources.create("business_kit", {"key": cat["key"], "label_en": cat["en"], "label_te": cat["te"],
                                          "order": order * 100}, actor="system:seed", status="ACTIVE")
        count += 1
        for i, s in enumerate(cat["subs"]):
            data = {"key": s["key"], "parent": cat["key"], "label_en": s["en"], "label_te": s["te"],
                    "flows": s["flows"], "shop_kind": s["kind"], "catalogue_template": s["catalogue"],
                    "details": s["details"], "customer_questions": s["asks"], "try_on": s["try_on"],
                    "try_on_note": s["try_on_note"], "high_stakes": s["high_stakes"], "order": i}
            resources.create("business_kit", {k: v for k, v in data.items() if v not in ("", [], None)} | {
                "key": s["key"], "parent": cat["key"], "label_en": s["en"]}, actor="system:seed", status="ACTIVE")
            count += 1
    return count
